def main(argv: list[str]) -> int:
    paper = Path(argv[1]).resolve() if len(argv) > 1 else Path.cwd()
    data = paper / "data"
    out = paper / "code" / "verify_numbers.py"
    if not (paper / "main.tex").exists():
        print(f"no main.tex under {paper}")
        return 2
    found = sorted(p.name for p in data.glob("*.json")) if data.is_dir() else []
    out.parent.mkdir(parents=True, exist_ok=True)

    # 从 data/*.json 里抽出可做断言的候选数字：只取数字型叶子，路径作标签。
    cands: list[tuple[str, float]] = []

    def walk(obj, path: str) -> None:
        if isinstance(obj, dict):
            for k, v in obj.items():
                walk(v, f"{path}.{k}" if path else str(k))
        elif isinstance(obj, list):
            for i, v in enumerate(obj[:3]):          # 只取前三个元素，避免爆量
                walk(v, f"{path}[{i}]")
        elif isinstance(obj, (int, float)) and not isinstance(obj, bool):
            cands.append((path, float(obj)))

    for name in found:
        try:
            walk(json.loads((data / name).read_text(encoding="utf-8")), name)
        except json.JSONDecodeError:
            continue

    listing = "\n".join(f"#   {p} = {v!r}" for p, v in cands[:40]) or "#   (no numeric leaves found)"
    head = (
        f'# data files present: {found or "NONE"}\n'
        f"# numeric leaves sampled ({len(cands)} total, first 40):\n{listing}\n\n"
    )
    (out).write_text(
        TEMPLATE_HEAD.replace("def main() -> int:\n    tex =",
                             head + "def main() -> int:\n    tex =", 1),
        encoding="utf-8")
    print(f"wrote {out}  ({len(cands)} numeric leaves sampled from {len(found)} file(s))")
    if not found:
        print("WARNING: no data/*.json yet -- the generator wrote a skeleton that will exit 2")

    # 顺手补齐会被各位成员覆盖的骨架文件。已存在的一律不覆盖（可能是成员写好的）。
    for rel, text in STUBS.items():
        dst = paper / rel
        if dst.exists():
            print(f"  keep existing {rel}")
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text, encoding="utf-8")
        print(f"  stub {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))