def in_context(tex: str, needle: str, window: int = 90) -> bool:
    """The needle appears as a standalone token, not inside a longer number.

    The context window is advisory only. Measured on the fixture: 0.0132 and
    0.9979 are genuinely in the text, yet a "must carry a unit marker nearby"
    rule called them missing. A token match is the claim; context is the note.
    """
    if needle is None:
        return True
    pat = r"(?<![\\d.])" + re.escape(needle) + r"(?!\\d)"
    return re.search(pat, tex) is not None


def main() -> int:
    tex = TEX.read_text(encoding="utf-8")
    jsons = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in DATA.glob("*.json")}
    if not jsons:
        print("no data/*.json: nothing to reconcile, refusing to report a pass")
        return 2

    claims = []           # (label, actual, expected, needle) -- every one is counted
    extra = []            # booleans that are asserted but are not numeric claims
    fails = []

    for label, actual, expected, needle in claims:
        tol = max(0.011, abs(expected) * 0.01)
        json_ok = abs(float(actual) - float(expected)) <= tol
        tex_ok = in_context(tex, needle)
        if not (json_ok and tex_ok):
            fails.append(f"{label}: json={actual} expected={expected} tex={tex_ok}")

    for desc, ok in extra:
        if not ok:
            fails.append(f"{desc}: assertion failed")

    print(f"{len(claims)} claims checked; {len(fails)} failures")
    for f in fails:
        print("  FAIL", f)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
