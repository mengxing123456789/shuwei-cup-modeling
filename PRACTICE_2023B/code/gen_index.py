"""Regenerate figures/code_index.tex from the file sizes on disk.

The table in the paper lists every script with its size in bytes.  A size
typed by hand goes stale the next time someone edits a script, and the paper
then claims a number that contradicts its own listing.  So the table has one
author: this script, reading st_size at generation time.

Layout contract (do not change without reading pipeline.py:549)
---------------------------------------------------------------
A row is exactly

    \\texttt{<file>} & <bytes> & <role>\\\\

<file> is the bare name with a literal underscore, <bytes> carries a literal
comma for thousands (19,793).  The pipeline gate G17 scans this file with
r"\\\\texttt\\{([\\w\\-.]+)\\}\\s*&\\s*([\\d,]+)" and compares the number it
finds to f"{size:,}"; an escaped name (\\_) or a braced number (19{,}793)
makes the gate match nothing and pass vacuously.  --check re-runs that same
scan, so a change that would blind the gate fails here first.

The file ends with \\bottomrule on purpose: if \\\\ were the last token, TeX
would hit ! Misplaced \\noalign at the closing parenthesis of the table and
stop after 30 pages.  main.tex therefore adds no rule of its own after
\\input, and wraps the table in \\begingroup\\catcode`\\_=12 so the literal
underscores print as underscores.

Exit codes: 0 current, 1 stale or unreadable, 2 current but not wired into
main.tex yet (the table exists, the paper does not show it).
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

WORKSPACE = pathlib.Path(__file__).resolve().parents[1]
CODE = WORKSPACE / "code"
TARGET = WORKSPACE / "figures" / "code_index.tex"
TOTALS = WORKSPACE / "figures" / "code_totals.tex"
MAIN = WORKSPACE / "main.tex"

# What each script produces, in the paper's own vocabulary.  A new script
# without a role is an error rather than a blank cell: the table is the only
# place where a reader learns what produced a number.
ROLE: dict[str, str] = {
    "check_figures.py": "figure gate: size, font, margins",
    "check_md.py": "report gate: calibers, pointers, column counts",
    "check_no_peek.py": "provenance guard: no reference to other papers",
    "fetch_annex.py": "data ledger: build and replay the annex tables",
    "fix_bytes.py": "rewrites the BYTES header of a report from disk",
    "gen_appendix.py": "notation table from model_skeleton.SYMBOLS",
    "gen_index.py": "this table, from the sizes on disk",
    "make_figures.py": "all sixteen figures, from data/results_*.json",
    "mk_appendix_src.py": "ASCII copies of the scripts for the listing",
    "model_skeleton.py": "constants, symbols, data contract",
    "numlib.py": "linear algebra that avoids BLAS and LAPACK",
    "s3_deliver.py": "timing, binding constraints, perturbation runs",
    "seal.py": "caption seals: escaped provenance lines",
    "solve.py": "Q1-Q5 solvers, writes data/results_q*.json",
    "verify_numbers.py": "number ledger: paper figures against data/*.json",
}

G17 = re.compile(r"\\texttt\{([\w\-.]+)\}\s*&\s*([\d,]+)")
RULE_AFTER_INPUT = re.compile(r"\\input\{figures/code_index\.tex\}(.*?)\\end\{tabular\}", re.S)

# Every self-referential number this report quotes, so that one command
# reprints all of them instead of trusting a table typed by hand.
AUDIT = (
    "code/solve.py",
    "code/check_no_peek.py",
    "NO_PEEK.md",
    "main.tex",
    "out/01-model.md",
    "out/02-solve.md",
    "out/03-numbers.md",
    "out/08-figures.md",
    "problem/problem.txt",
)
CJK_RE = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3000-\u303f\uff01-\uff60\uffe0-\uffe6]")

HEAD = [
    "% generated by code/gen_index.py -- do not edit",
    "% regenerate: E:/Mini/envs/mathmodel/python.exe -X utf8 code/gen_index.py",
    "% main.tex owns \\toprule, the header row and the closing: this file owns the rows and \\bottomrule",
]


def scripts() -> list[pathlib.Path]:
    """Every code/*.py that is part of the paper, in a stable order.

    Leading-underscore files are scratch probes: they are not shipped and
    their sizes move between runs, so they never enter the table.
    """
    return sorted(p for p in CODE.glob("*.py") if not p.name.startswith("_"))


def rows() -> tuple[list[str], list[str]]:
    """(row lines, names) built from disk; raises on a script with no role."""
    out: list[str] = []
    names: list[str] = []
    missing: list[str] = []
    for path in scripts():
        role = ROLE.get(path.name)
        if role is None:
            missing.append(path.name)
            continue
        size = path.stat().st_size
        out.append(f"\\texttt{{{path.name}}} & {size:,} & {role}\\\\")
        names.append(path.name)
    if missing:
        raise SystemExit(
            "gen_index.py: no role for " + ", ".join(missing)
            + " -- add the line to ROLE in code/gen_index.py so the table can describe it"
        )
    return out, names


def render() -> str:
    body, names = rows()
    total = sum((CODE / name).stat().st_size for name in names)
    head = [
        *HEAD,
        f"% {len(names)} scripts, {total:,} bytes in total; sizes read from disk at generation time",
    ]
    return "\n".join(head + body + [r"\bottomrule"]) + "\n"


def totals() -> tuple[str, int, int]:
    """(tex for figures/code_totals.tex, script count, total bytes)."""
    body, names = rows()
    total = sum((CODE / name).stat().st_size for name in names)
    tex = "\n".join([
        "% generated by code/gen_index.py -- do not edit",
        f"\\providecommand{{\\CodeIndexCount}}{{{len(names)}}}",
        f"\\providecommand{{\\CodeIndexBytes}}{{{total:,}}}",
        "\\providecommand{\\CodeIndexSummary}{\\CodeIndexCount{} scripts, \\CodeIndexBytes{} bytes}",
    ]) + "\n"
    return tex, len(names), total


MACROS = ("\\CodeIndexSummary", "\\CodeIndexCount", "\\CodeIndexBytes")


def check() -> int:
    """Compare disk with the rendered table, then re-run the G17 scan."""
    if not TARGET.exists():
        print(f"gen_index.py: {TARGET.name} is missing -- run code/gen_index.py")
        return 1
    on_disk = TARGET.read_text(encoding="utf-8")
    want = render()
    if on_disk != want:
        old = on_disk.splitlines()
        new = want.splitlines()
        for i, (a, b) in enumerate(zip(old, new), 1):
            if a != b:
                print(f"STALE {TARGET.name}:{i}\n  on disk: {a}\n  on file: {b}")
                break
        else:
            print(f"STALE {TARGET.name}: {len(old)} lines on disk, {len(new)} expected")
        return 1

    seen: dict[str, str] = {}
    for name, printed in G17.findall(on_disk):
        seen[name] = printed
    bad = 0
    for path in scripts():
        printed = seen.get(path.name)
        if printed is None:
            print(f"G17 would not see {path.name}: no \\texttt{{{path.name}}} & <bytes> row")
            bad += 1
            continue
        truth = f"{path.stat().st_size:,}"
        if printed != truth:
            print(f"G17 mismatch {path.name}: table says {printed}, disk says {truth}")
            bad += 1
    for name in seen:
        if not (CODE / name).exists():
            print(f"G17 would read code/{name}, which does not exist")
            bad += 1
    if bad:
        return 1
    print(f"row check: {len(seen)}/{len(scripts())} rows match disk, G17 scan clean")

    tex, count, total = totals()
    if not TOTALS.exists():
        print(f"MISSING {TOTALS.name}: the caption macros \\CodeIndexCount / \\CodeIndexBytes "
              f"({count} scripts, {total:,} bytes) have nowhere to come from")
        return 1
    if TOTALS.read_text(encoding="utf-8") != tex:
        print(f"STALE {TOTALS.name}: should say {count} scripts, {total:,} bytes")
        return 1

    if not MAIN.exists():
        print("main.tex is missing")
        return 1
    main = MAIN.read_text(encoding="utf-8")
    if "\\input{figures/code_index.tex}" not in main:
        print("NOT WIRED: main.tex has no \\input{figures/code_index.tex}, so the table "
              "is a dead file (G15) and the paper shows no code index")
        return 2
    match = RULE_AFTER_INPUT.search(main)
    if match and "\\bottomrule" in match.group(1):
        print("main.tex puts \\bottomrule after the \\input: the generated file already "
              "ends the table, a second rule is ! Misplaced \\noalign")
        return 1
    used = [m for m in MACROS if m in main]
    if used and "\\input{figures/code_totals.tex}" not in main:
        print(f"main.tex uses {used[0]} but never inputs figures/code_totals.tex: "
              f"! Undefined control sequence")
        return 1
    if used:
        lines = main.splitlines()
        at = next(i for i, l in enumerate(lines) if "\\input{figures/code_totals.tex}" in l)
        opened = None
        for i, l in enumerate(lines[:at]):
            if "\\begingroup" in l:
                opened = i
            if "\\endgroup" in l:
                opened = None
        if opened is not None:
            close = next((i for i in range(at, len(lines)) if "\\endgroup" in lines[i]), None)
            late = [i + 1 for i in range((close + 1) if close is not None else at, len(lines))
                    if any(m in lines[i] for m in MACROS)]
            if late:
                print(f"main.tex inputs figures/code_totals.tex inside the \\begingroup opened at "
                      f"line {opened + 1} but uses a macro after it at line {late[0]}: "
                      f"\\providecommand is local, so that use is ! Undefined control sequence "
                      f"(move the \\input above the \\begingroup)")
                return 1
    print("wiring: main.tex inputs figures/code_index.tex and adds no rule of its own")
    return 0


def audit() -> int:
    """Print every product-determined number of this report, read from disk."""
    print("file                     lines    bytes")
    for rel in AUDIT:
        path = WORKSPACE / rel
        if not path.exists():
            print(f"{rel:24s} missing")
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        print(f"{rel:24s}{len(text.splitlines()):5d}{path.stat().st_size:9,d}")

    main = MAIN.read_text(encoding="utf-8") if MAIN.exists() else ""
    live = "\n".join(line.split("%")[0] for line in main.splitlines())
    sections = len(re.findall(r"\\section\*?\{", live))
    subsections = len(re.findall(r"\\subsection\*?\{", live))
    placeholders = len(re.findall(r"<<[^>]*>>", main))
    digits = len(re.findall(r"[0-9]+", live))
    print(f"main.tex: sections {sections}, subsections {subsections}, "
          f"placeholders {placeholders}, digit tokens outside comments {digits}")
    wired = "figures/code_index.tex" in main
    print(f"main.tex: tab:code {'yes' if 'tab:code' in main else 'no'}, "
          f"inputs figures/code_index.tex {'yes' if wired else 'no'}")
    tot_lines = main.splitlines()
    tot_at = next((i + 1 for i, l in enumerate(tot_lines)
                   if "\\input{figures/code_totals.tex}" in l), None)
    if tot_at is None:
        print("main.tex: never inputs figures/code_totals.tex")
    else:
        opened = None
        for i, l in enumerate(tot_lines[:tot_at]):
            if "\\begingroup" in l:
                opened = i + 1
            if "\\endgroup" in l:
                opened = None
        where = (f"INSIDE the \\begingroup opened at line {opened}: \\providecommand is local, "
                 f"so any use after \\endgroup is ! Undefined control sequence"
                 if opened else "outside every \\begingroup: the macros stay global")
        print(f"main.tex: code_totals input at line {tot_at}, {where}")
    if "\\begin{document}" in main:
        body = main.split("\\begin{document}", 1)[1]
        first = main[:main.index("\\begin{document}")].count("\n") + 1
        hits = [(first + i, line.strip()) for i, line in enumerate(body.splitlines(), 1)
                if CJK_RE.search(line)]
        if hits:
            print(f"main.tex: {len(hits)} line(s) with CJK after \\begin{{document}} "
                  f"(check_chinese reports the first: line {hits[0][0]})")
            for lineno, line in hits[:3]:
                print(f"  line {lineno}: {line[:60]}")
        else:
            print("main.tex: no CJK after \\begin{document}")

    figs = sorted((WORKSPACE / "figures").glob("*"))
    pdfs = [p for p in figs if p.suffix == ".pdf"]
    pngs = [p for p in figs if p.suffix == ".png"]
    texs = [p for p in figs if p.suffix == ".tex"]
    top = len(figs)
    seals = sorted((WORKSPACE / "figures").glob("*.seal.tex"))
    src = sorted((WORKSPACE / "figures" / "src").glob("*.py")) if (WORKSPACE / "figures" / "src").exists() else []
    print(f"figures/: {len(pdfs)} pdf, {len(pngs)} png, {len(texs)} tex "
          f"{[p.name for p in texs]}, {top} entries")
    print(f"seals: {len(seals)} of {len(pdfs)} figure PDFs have a .seal.tex")
    print(f"figures/src: {len(src)} ASCII copies, {sum(p.stat().st_size for p in src):,} bytes")

    if TARGET.exists():
        text = TARGET.read_text(encoding="utf-8")
        print(f"code_index.tex: {TARGET.stat().st_size:,} bytes, "
              f"{len(text.splitlines())} lines, "
              f"{len(G17.findall(text))} of {len(scripts())} rows visible to G17")

    # The two sites the ASCII conversion cannot rewrite; re-derived live.
    try:
        import mk_appendix_src
    except Exception as exc:  # noqa: BLE001
        print(f"appendix copies: cannot import mk_appendix_src ({exc})")
        return 0
    for name in ("solve.py", "verify_numbers.py"):
        _, stats, problems = mk_appendix_src.convert_file(CODE / name)
        print(f"{name}: {stats['cjk_before']} non-ASCII -> "
              + ("refused: " + " | ".join(problems) if problems else "convertible"))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="regenerate figures/code_index.tex")
    ap.add_argument("--check", action="store_true", help="fail if the table on disk is stale")
    ap.add_argument("--audit", action="store_true", help="print the product-determined numbers")
    ap.add_argument("--print", dest="show", action="store_true", help="print without writing")
    args = ap.parse_args(argv)
    if args.audit:
        return audit()
    if args.check:
        return check()
    text = render()
    if args.show:
        sys.stdout.write(text)
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    tot, count, total = totals()
    TOTALS.write_text(tot, encoding="utf-8", newline="\n")
    body, names = rows()
    print(f"wrote {TARGET} ({TARGET.stat().st_size:,} bytes): {len(body)} scripts, {total:,} bytes of code")
    print(f"wrote {TOTALS} ({TOTALS.stat().st_size:,} bytes): \\CodeIndexCount {count}, "
          f"\\CodeIndexBytes {total:,}")
    main_text = MAIN.read_text(encoding="utf-8") if MAIN.exists() else ""
    if "\\input{figures/code_index.tex}" not in main_text:
        print("WARN main.tex does not input this table yet: the paper will show no code "
              "index and G15 will call figures/code_index.tex a dead file", file=sys.stderr)
    if not any(m in main_text for m in MACROS):
        print("NOTE main.tex does not use \\CodeIndexSummary: the caption must not state "
              "a script count or a byte total of its own", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())