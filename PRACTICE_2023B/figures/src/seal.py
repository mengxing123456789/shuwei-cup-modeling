"""Caption seals for the figures: buffer stamp()/header() calls, flush on save().

Why a buffer at all
-------------------
In this paper a figure function reads its numbers from data/results_*.json,
then calls save().  The provenance line under the caption ("42 runs,
8.0% worst case, mip_gap=0") is only known *before* save() runs, while the
file name is only known *inside* save().  Writing the line eagerly is
therefore impossible: stamp() and header() only queue text, save() calls
commit(), and commit() is the single place that turns text into a .tex file.

Why escaping is not optional
----------------------------
The same numbers carry `_`, `%`, `$`, `&`, `#`.  A seal written verbatim
turns `mip_gap=0` into "Missing $ inserted" and `8.0%` into a comment that
swallows the rest of the line; the build dies on page 30 and the paper looks
like it has 30 pages.  tex_escape() is applied to every line in commit(), so
no caller can forget it.

Usage (inside code/make_figures.py)
-----------------------------------
    from seal import stamp, header, commit

    def fig07_solute_budget(...):
        ...
        header(stem, "Q2: mass balance, all five species")
        stamp(stem, f"n = {n_runs} runs, mip_gap=0, worst gap {gap:.1f}%")
        save(fig, stem, "Solute budget")

    # inside save(), after the PDF/PNG are written:
    commit(stem, OUT / "figures")
"""
from __future__ import annotations

import argparse
import pathlib
import sys

# Escaped forms already claimed by save(); kept for the .tex of record.
STEM_SEAL: dict[str, list[str]] = {}
STEM_HEAD: dict[str, str] = {}

# Calls made before save() lands here.  Keyed by stem, so a figure that
# stamps twice for two stems cannot leak into the wrong caption.
_PENDING_SEAL: dict[str, list[str]] = {}
_PENDING_HEAD: dict[str, str] = {}

_TEX_MAP = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}

_SPECIALS = "_%&#$"


def tex_escape(text: str) -> str:
    """Make one line safe for LaTeX text mode.

    Escaping is per character through _TEX_MAP, so an inserted command can
    never be re-scanned.  " m2" is the one substitution that spans several
    characters: a bare 2 after m reads as a footnote marker, and reviewer
    tables quote areas as m2.
    """
    parts = text.split(" m2")
    return r" m\textsuperscript{2}".join(_esc(part) for part in parts)


def _esc(part: str) -> str:
    return "".join(_TEX_MAP.get(ch, ch) for ch in part)


def _unescaped(line: str) -> list[str]:
    """Special characters in `line` that no backslash is currently defending."""
    hits = []
    for i, ch in enumerate(line):
        if ch not in _SPECIALS:
            continue
        run = 0
        j = i - 1
        while j >= 0 and line[j] == "\\":
            run += 1
            j -= 1
        if run % 2 == 0:
            hits.append(ch)
    return hits


def stamp(stem: str, *lines: str) -> None:
    """Queue provenance lines for the seal of `stem`."""
    if not lines:
        return
    _PENDING_SEAL.setdefault(stem, []).extend(lines)


def header(stem: str, text: str) -> None:
    """Queue the one-line heading that sits above the provenance lines."""
    _PENDING_HEAD[stem] = text


def pending() -> dict[str, int]:
    """What is still queued; a figure that forgets save() shows up here."""
    return {stem: len(lines) for stem, lines in sorted(_PENDING_SEAL.items())}


def _non_ascii(text: str) -> str:
    return "".join(sorted({ch for ch in text if ord(ch) > 127}))


def commit(stem: str, tex_dir: pathlib.Path | str, origin: str = "code/make_figures.py") -> pathlib.Path:
    """Write <tex_dir>/<stem>.seal.tex from the queued lines; return its path.

    The file is written even when nothing was queued: an empty caption is a
    visible bug, a missing file is a build error 30 pages later.
    """
    lines = _PENDING_SEAL.pop(stem, [])
    head = _PENDING_HEAD.pop(stem, "")
    STEM_SEAL[stem] = [tex_escape(line) for line in lines]
    STEM_HEAD[stem] = tex_escape(head) if head else ""

    bad = _non_ascii(" ".join(lines) + " " + head)
    if bad:
        print(f"WARN seal {stem}: non-ASCII {bad!r} reaches the PDF as Chinese text; "
              f"rewrite the line in English", file=sys.stderr)

    body = STEM_SEAL[stem]
    text = f"% generated by {origin} -- do not edit\n"
    if STEM_HEAD[stem]:
        text += STEM_HEAD[stem] + "\n"
    if body:
        text += "\n" + "\n\n".join(body) + "\n"
    path = pathlib.Path(tex_dir) / f"{stem}.seal.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


# --------------------------------------------------------------------------
# Self-checks: the escaping table is the only thing standing between a number
# and a dead build, so it is pinned by literals rather than by eyeballing.
_CASES: list[tuple[str, str]] = [
    ("mip_gap=0", r"mip\_gap=0"),
    ("8.0%", r"8.0\%"),
    ("CH$_4$", r"CH\$\_4\$"),
    ("A & B", r"A \& B"),
    ("#3", r"\#3"),
    ("~1e-6", r"\textasciitilde{}1e-6"),
    ("x^2", r"x\textasciicircum{}2"),
    ("area 0.5 m2", r"area 0.5 m\textsuperscript{2}"),
    ("a{b}c", r"a\{b\}c"),
    (r"C:\tmp", r"C:\textbackslash{}tmp"),
]


def selftest() -> int:
    bad = 0
    for raw, want in _CASES:
        got = tex_escape(raw)
        if got != want:
            print(f"FAIL tex_escape({raw!r}) -> {got!r}, want {want!r}")
            bad += 1
    if bad:
        return 1
    for raw, _ in _CASES:
        escaped = tex_escape(raw)
        left = _unescaped(escaped)
        if left:
            print(f"FAIL residual special character {left} in {escaped!r}")
            bad += 1
    print(f"ok {len(_CASES)} escape cases")
    return 0


def check(tex_dir: pathlib.Path | str, expect: int | None = None) -> int:
    """Residue scan over the seals on disk; 0 clean, 1 dirty.

    Every line must have gone through tex_escape, so a bare $ is a hit too:
    a seal is prose about numbers, not a formula.
    """
    tex_dir = pathlib.Path(tex_dir)
    files = sorted(tex_dir.glob("*.seal.tex"))
    print(f"seals on disk: {len(files)}")
    bad = 0
    for path in files:
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if lineno == 1 or line.startswith("%"):
                continue
            hit = _unescaped(line)
            if hit:
                print(f"{path.name}:{lineno}: unescaped {hit} in {line[:90]!r}")
                bad += 1
    if expect is not None and len(files) != expect:
        print(f"MISSING seals: {len(files)} of {expect} stems have a .seal.tex")
        bad += 1
    return 1 if bad else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="caption seals for figures/*.seal.tex")
    ap.add_argument("--selftest", action="store_true", help="pin the escape table")
    ap.add_argument("--check", nargs="?", const="figures", metavar="TEX_DIR",
                    help="scan existing .seal.tex for unescaped characters")
    ap.add_argument("--expect", type=int, default=None, help="number of stems that should have a seal")
    args = ap.parse_args(argv)
    rc = 0
    if args.selftest:
        rc = max(rc, selftest())
    if args.check:
        rc = max(rc, check(args.check, args.expect))
    if not args.selftest and not args.check:
        ap.print_help()
    return rc


if __name__ == "__main__":
    raise SystemExit(main())